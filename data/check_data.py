"""Check that every data file in the repo is listed in data/manifest.json and traceable.

The rule this checks: AI can write the script that gets the data. It can't
write the data. Every dataset is either fetched by a script from a cited
source, generated by a deterministic script and labelled fictional, or
hand-entered with a source on every record.

Run from the repo root:

    python data/check_data.py                 # manifest, files, checksums, record sources
    python data/check_data.py --sample 5      # also print 5 random records per traceable dataset
    python data/check_data.py --rerun         # also re-run synthetic scripts and compare output
    python data/check_data.py --refetch       # also re-run fetched scripts (needs internet)
    python data/check_data.py --write-checksums   # record current checksums in the manifest
    python data/check_data.py --json          # machine-readable report

--rerun and --refetch run the scripts named in the manifest, on a temporary
copy of the repo. Only use them on a repo you trust, or inside a sandbox.

Findings are reported, not judged. FLAG means a judge should look.
WARN is worth a glance. Judges decide what a flag means for the score.
Exit code is 1 if there are any FLAG findings, otherwise 0.
Needs only Python 3 and its standard library.
"""

import argparse
import csv
import hashlib
import json
import random
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
MANIFEST = DATA / "manifest.json"

KINDS = {"fetched", "synthetic", "hand_entered"}
REQUIRED = {
    "fetched": ["id", "kind", "description", "files", "script", "source_name", "source_url",
                "license", "retrieved"],
    "synthetic": ["id", "kind", "description", "files", "script", "license", "fictional"],
    "hand_entered": ["id", "kind", "description", "files", "license", "record_source_field"],
}
# The Fergie seed ships without its generator: the script would give away what the judging
# walkthrough looks for. Its checksums still catch any edit. Only the track's own seed gets this.
TRACK_PROVIDED = {"fergie-seed"}
# Files under data/ that are code or docs, not data.
NOT_DATA_SUFFIXES = {".md", ".py", ".js", ".mjs", ".cjs", ".ts", ".sh", ".ps1"}
NOT_DATA_NAMES = {"manifest.json", ".gitignore", ".gitkeep", ".gitattributes", "LICENSE",
                  ".DS_Store", "Thumbs.db", "desktop.ini"}
SKIP_DIRS = {".git", "node_modules", ".venv", "venv", "__pycache__", "dist", "build", ".next",
             ".nuxt", ".svelte-kit", "coverage", "target", "vendor"}
# Outside data/, these look like datasets and get a warning.
DATA_LIKE_SUFFIXES = {".csv", ".tsv", ".geojson", ".jsonl", ".ndjson", ".sqlite", ".sqlite3",
                      ".db", ".parquet", ".xlsx"}
BIG_JSON_BYTES = 100_000
NOT_DATA_JSON = {"package.json", "package-lock.json", "tsconfig.json", "composer.json",
                 "composer.lock", "manifest.json"}


class Report:
    def __init__(self):
        self.items = []

    def add(self, level, dataset, message):
        self.items.append({"level": level, "dataset": dataset, "message": message})

    def count(self, level):
        return sum(1 for i in self.items if i["level"] == level)


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def walk(base):
    for path in sorted(base.rglob("*")):
        if any(part in SKIP_DIRS for part in path.relative_to(ROOT).parts):
            continue
        if path.is_file():
            yield path


def rel(path):
    return path.relative_to(ROOT).as_posix()


def load_records(path, records_key=None):
    """Return a list of records from a JSON or CSV file, or None if it has no obvious records."""
    if path.suffix == ".csv":
        with open(path, encoding="utf-8", newline="") as f:
            return list(csv.DictReader(f))
    if path.suffix != ".json":
        return None
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    if records_key:
        for key in records_key.split("."):
            data = data.get(key, []) if isinstance(data, dict) else []
    if isinstance(data, list):
        return data
    return None


def check_manifest(report):
    if not MANIFEST.exists():
        report.add("FLAG", "-", "data/manifest.json is missing. No data in this repo can be traced.")
        return None
    try:
        with open(MANIFEST, encoding="utf-8") as f:
            manifest = json.load(f)
    except json.JSONDecodeError as e:
        report.add("FLAG", "-", f"data/manifest.json is not valid JSON: {e}")
        return None
    datasets = manifest.get("datasets")
    if not isinstance(datasets, list) or not datasets:
        report.add("FLAG", "-", "data/manifest.json has no datasets listed.")
        return None
    return manifest


def check_dataset(report, ds, sample):
    name = ds.get("id", "(no id)")
    kind = ds.get("kind")
    if kind not in KINDS:
        report.add("FLAG", name, f"kind is {kind!r}. Use one of: {', '.join(sorted(KINDS))}.")
        return
    missing = [k for k in REQUIRED[kind] if ds.get(k) in (None, "", [])]
    if name in TRACK_PROVIDED:
        missing = [k for k in missing if k != "script"]
    if missing:
        report.add("FLAG", name, f"missing fields for a {kind} dataset: {', '.join(missing)}")
    if kind == "synthetic" and ds.get("fictional") is not True:
        report.add("FLAG", name, "synthetic data must say fictional: true")
    script = ds.get("script")
    if script and not (ROOT / script).is_file():
        report.add("FLAG", name, f"script not found: {script}")

    checksums = ds.get("checksums") or {}
    for f in ds.get("files") or []:
        path = ROOT / f
        if not path.is_file():
            report.add("FLAG", name, f"listed file not found: {f}")
            continue
        expected = checksums.get(f)
        if not expected:
            report.add("WARN", name, f"no checksum recorded for {f}")
        elif expected != sha256(path):
            report.add("FLAG", name, f"{f} has changed since its checksum was recorded "
                                     "(edited by hand, or not regenerated with its script)")

        field = ds.get("record_source_field")
        if field or sample:
            try:
                records = load_records(path, ds.get("records_key"))
            except (json.JSONDecodeError, UnicodeDecodeError) as e:
                report.add("FLAG", name, f"{f} could not be read: {e}")
                continue
            if records is None:
                if field:
                    report.add("WARN", name, f"{f}: couldn't find a list of records to check "
                                             "(set records_key in the manifest)")
                continue
            if field:
                bad = [i for i, r in enumerate(records)
                       if not isinstance(r, dict) or r.get(field) in (None, "", [], {})]
                if bad:
                    report.add("FLAG", name, f"{f}: {len(bad)} of {len(records)} records have no "
                                             f"{field!r} (first at index {bad[0]})")
                else:
                    report.add("OK", name, f"{f}: all {len(records)} records have {field!r}")
            if sample and kind in {"fetched", "hand_entered"} and records:
                picks = random.Random(f).sample(records, min(sample, len(records)))
                for r in picks:
                    report.add("SAMPLE", name, json.dumps(r, ensure_ascii=False)[:600])


def check_unlisted(report, manifest):
    listed = {f for ds in (manifest or {}).get("datasets", []) for f in ds.get("files") or []}
    for path in walk(DATA):
        if path.suffix in NOT_DATA_SUFFIXES or path.name in NOT_DATA_NAMES:
            continue
        if rel(path) not in listed:
            report.add("FLAG", "-", f"{rel(path)} is in data/ but not listed in the manifest")
    for path in walk(ROOT):
        if path.is_relative_to(DATA):
            continue
        big_json = (path.suffix == ".json" and path.name not in NOT_DATA_JSON
                    and path.stat().st_size > BIG_JSON_BYTES)
        if path.suffix in DATA_LIKE_SUFFIXES or big_json:
            report.add("WARN", "-", f"{rel(path)} looks like data but lives outside data/. "
                                    "If it is data, move it to data/ and list it.")


def rerun(report, manifest, kinds):
    for ds in manifest.get("datasets", []):
        if ds.get("kind") not in kinds or not ds.get("script"):
            continue
        name = ds["id"]
        with tempfile.TemporaryDirectory() as tmp:
            tmp_root = Path(tmp)
            # Parents first: if the script's folder sits inside data/, copying it first would
            # stop the rest of data/ being copied, and scripts that read other datasets would fail.
            for folder in sorted({DATA, (ROOT / ds["script"]).parent}, key=lambda f: len(f.parts)):
                dest = tmp_root / folder.relative_to(ROOT)
                if not dest.exists():
                    shutil.copytree(folder, dest, ignore=shutil.ignore_patterns(*SKIP_DIRS))
            # Remove the dataset's own files from the copy, so a script that writes nothing can't pass.
            for f in ds.get("files") or []:
                (tmp_root / f).unlink(missing_ok=True)
            result = subprocess.run([sys.executable, ds["script"]], cwd=tmp_root,
                                    capture_output=True, text=True, timeout=600)
            if result.returncode != 0:
                report.add("FLAG", name, f"script failed: {result.stderr.strip()[-400:]}")
                continue
            for f in ds.get("files") or []:
                new = tmp_root / f
                if not new.is_file():
                    report.add("FLAG", name, f"script did not produce {f}")
                elif not (ROOT / f).is_file():
                    continue
                elif sha256(new) == sha256(ROOT / f):
                    report.add("OK", name, f"re-running the script reproduces {f} exactly")
                elif ds["kind"] == "synthetic":
                    report.add("FLAG", name, f"re-running the script gives a different {f}. "
                                             "The committed file wasn't made by this script as-is.")
                else:
                    report.add("WARN", name, f"re-fetching gives a different {f}. The source may "
                                             "have changed since it was retrieved, so compare them.")


def write_checksums(manifest):
    for ds in manifest.get("datasets", []):
        ds["checksums"] = {f: sha256(ROOT / f) for f in ds.get("files") or [] if (ROOT / f).is_file()}
    with open(MANIFEST, "w", encoding="utf-8", newline="\n") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print("Checksums written to data/manifest.json")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--sample", type=int, default=0, help="print N random records per traceable dataset")
    parser.add_argument("--rerun", action="store_true", help="re-run synthetic scripts and compare")
    parser.add_argument("--refetch", action="store_true", help="re-run fetched scripts and compare")
    parser.add_argument("--write-checksums", action="store_true", help="record current checksums")
    parser.add_argument("--json", action="store_true", help="print the report as JSON")
    args = parser.parse_args()

    report = Report()
    manifest = check_manifest(report)
    if manifest and args.write_checksums:
        write_checksums(manifest)
        return 0
    if manifest:
        for ds in manifest["datasets"]:
            check_dataset(report, ds, args.sample)
        kinds = ({"synthetic"} if args.rerun else set()) | ({"fetched"} if args.refetch else set())
        if kinds:
            rerun(report, manifest, kinds)
    check_unlisted(report, manifest)

    if args.json:
        print(json.dumps({"flags": report.count("FLAG"), "warnings": report.count("WARN"),
                          "items": report.items}, ensure_ascii=False, indent=2))
    else:
        for i in report.items:
            print(f"{i['level']:<7} {i['dataset']:<24} {i['message']}")
        print(f"\n{report.count('FLAG')} flag(s), {report.count('WARN')} warning(s)")
    return 1 if report.count("FLAG") else 0


if __name__ == "__main__":
    sys.exit(main())
